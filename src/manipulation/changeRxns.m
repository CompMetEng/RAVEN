function model=changeRxns(model,rxns,equations,varargin)
% changeRxns  Modify the equations of reactions in a model.
%
% Parameters
% ----------
% model : struct
%     a model structure.
% rxns : cell
%     cell array with reaction ids.
% equations : cell or struct
%     cell array with equations, or a structure with the fields "mets" and
%     "stoichCoeffs" as in addRxns, for example:
%
%     - equations.mets = {{"met1","met2"},{"met1","met3"}}
%     - equations.stoichCoeffs = {[-1,+2],[-1,+1]}
%
% Name-Value Arguments
% --------------------
% eqnType : double
%     the interpretation of the equation strings (default 1):
%
%     - 1 : the metabolites are matched to model.mets. New metabolites (if
%       allowed) are added to "compartment".
%     - 2 : the metabolites are matched to model.metNames and all
%       metabolites are assigned to "compartment". New metabolites get
%       ids generated by generateNewIds with the prefix "m_", numbered from the
%       highest existing number with that prefix plus 1.
%     - 3 : the metabolites are written as "metNames[comps]". Only
%       compartments in model.comps are allowed. New metabolites get ids
%       generated in the same way as for eqnType 2.
% compartment : char
%     the compartment of the metabolites for eqnType=2 and of new metabolites for
%     eqnType=1. Must match model.comps. Not used for eqnType=3.
% allowNewMets : logical
%     true to allow the function to add new metabolites. The function calls addMets
%     with copyInfo true, so a new metabolite takes the charge and deltaG from a
%     metabolite with the same name in another compartment, and InChI, SMILES,
%     formula and MIRIAM annotation from it when its own are empty. When the
%     annotation of new metabolites is to be set explicitly, or when they are to be
%     exchange (unconstrained) metabolites, adding them with addMets first gives
%     that control (default false).
%
% Returns
% -------
% model : struct
%     an updated model structure.
%
% Examples
% --------
%     model = changeRxns(model, rxns, equations, eqnType, compartment, allowNewMets);
%
% Notes
% -----
% The function keeps the bounds of the reactions. Changing an irreversible reaction to a
% reversible one, or the reverse, changes the model.rev field but not model.lb and
% model.ub, so the bounds still define the reversibility of the reaction. setParam
% changes the bounds.
%
% New metabolites receive the annotation of the metabolite with the same name in
% another compartment, when one exists (see allowNewMets).

p=parseRAVENargs(varargin, {'eqnType',1; 'compartment',[]; 'allowNewMets',false});
eqnType=p.eqnType;
compartment=p.compartment;
allowNewMets=p.allowNewMets;

rxns=convertCharArray(rxns);
compartment=char(compartment);

%Find the indexes of the reactions and throw an error if they are not all
%found
[I, J]=ismember(rxns,model.rxns);
if ~all(I)
    EM='All reaction ids must exist in the model';
    error('RAVEN:badInput', '%s', EM);
end

%The reactions are changed in the following manner. First create a
%rxns-structure by copying info from the model. Then remove the old
%reactions. Then add the updated ones using addRxns. Lastly, the model is
%reordered to match the original order. This is done like this to make use
%of the advanced parsing of equations that addRxns use.
rxnsToChange.rxns=rxns;
if isfield(equations,'mets') && isfield(equations,'stoichCoeffs')
    rxnsToChange.mets=equations.mets;
    rxnsToChange.stoichCoeffs=equations.stoichCoeffs;
else
    rxnsToChange.equations=convertCharArray(equations);
end
if isfield(model,'rxnNames')
    rxnsToChange.rxnNames=model.rxnNames(J);
end
if isfield(model,'lb')
    rxnsToChange.lb=model.lb(J);
end
if isfield(model,'ub')
    rxnsToChange.ub=model.ub(J);
end
if isfield(model,'c')
    rxnsToChange.c=model.c(J);
end
if isfield(model,'eccodes')
    rxnsToChange.eccodes=model.eccodes(J);
end
if isfield(model,'subSystems')
    rxnsToChange.subSystems=model.subSystems(J);
end
if isfield(model,'rxnComps')
    rxnsToChange.rxnComps=model.rxnComps(J);
end
if isfield(model,'grRules')
    rxnsToChange.grRules=model.grRules(J);
end
if isfield(model,'rxnFrom')
    rxnsToChange.rxnFrom=model.rxnFrom(J);
end
if isfield(model,'rxnScores')
    rxnsToChange.rxnScores=model.rxnScores(J);
end
if isfield(model,'rxnMiriams')
    rxnsToChange.rxnMiriams=model.rxnMiriams(J);
end
if isfield(model,'rxnNotes')
    rxnsToChange.rxnNotes=model.rxnNotes(J);
end
if isfield(model,'rxnReferences')
    rxnsToChange.rxnReferences=model.rxnReferences(J);
end
if isfield(model,'rxnConfidenceScores')
    rxnsToChange.rxnConfidenceScores=model.rxnConfidenceScores(J);
end
if isfield(model,'rxnDeltaG')
    rxnsToChange.rxnDeltaG=model.rxnDeltaG(J);
end
if isfield(model,'pwys')
    rxnsToChange.pwys=model.pwys(J);
end

%Calculate the new order of reactions
order=ones(numel(model.rxns),1);
order(J)=0;
order=cumsum(order);
order(J)=order(end)+1:order(end)+numel(rxns);

%Remove the original reactions
model=removeReactions(model,rxns);

model=addRxns(model,rxnsToChange,eqnType,compartment,allowNewMets);
model=permuteModel(model,order,'rxns');
end
